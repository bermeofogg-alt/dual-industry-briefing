def apply_swaps(sections, swaps):
    hit = set()
    for sec in sections:
        new_items = []
        for it in sec["items"]:
            if it["url"] in swaps:
                new_items.append(swaps[it["url"]])
                hit.add(it["url"])
            else:
                it["new"] = False  # 沿用条目一律不标新
                new_items.append(it)
        sec["items"] = new_items
    missing = set(swaps) - hit
    if missing:
        raise SystemExit(f"未匹配的旧URL: {missing}")

